
export type CategoryType = 'Mind' | 'Body' | 'Study' | 'Sleep' | 'Break' | 'Medicine';

export interface MainTask {
  name: string;
  targetDate: string; // ISO String
}

export interface Task {
  id: string;
  name: string;
  category: CategoryType;
  startTime: string; // ISO String
  durationMinutes: number;
  completed: boolean;
  isSpacedRepetition?: boolean;
  isQuick?: boolean; 
  isMedicine?: boolean; 
  repetitionStep?: number;
}

export interface UserStats {
  streak: number;
  xp: number;
  hydrationCount: number;
  lastHydrationUpdate: number;
  dailyCompletion: Record<string, number>; // "YYYY-MM-DD": percentage
  mainTask?: MainTask;
  dailyGoal?: { goal: string; date: string };
  focusSubjects?: { subject: string; endDate: string }[]; // NEW: Subject focus for next N days
}

export type PandaState = 'IDLE' | 'MEDITATING' | 'READING' | 'EXERCISING' | 'PLAYING' | 'SHOCKED' | 'HIDING' | 'SLEEPING';

export enum Tab {
  HOME = 'home',
  SCHEDULER = 'scheduler',
  SPACED = 'spaced',
  ANALYTICS = 'analytics',
  SETTINGS = 'settings',
  SENSEI = 'sensei',
  EXAM = 'exam'
}

